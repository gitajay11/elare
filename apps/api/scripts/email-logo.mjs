// Builds the logo that is embedded in every email (as an inline attachment, so
// it shows even when the website is unreachable) from the master artwork.
//
//   node apps/api/scripts/email-logo.mjs
//
// Writes src/emails/logo.ts. Re-run it whenever logo/elare logo.png changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(root, '..', '..');
// sharp is installed for the storefront's build; borrow it from there.
const sharp = createRequire(join(repo, 'node_modules', '.pnpm', 'node_modules', 'x.js'))('sharp');

const SIZE = 216; // shown at up to 72px: crisp on 3x phone screens
const png = await sharp(readFileSync(join(repo, 'logo', 'elare logo.png')))
  .resize(SIZE, SIZE, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .png({ palette: true, quality: 92, effort: 10, compressionLevel: 9 })
  .toBuffer();

writeFileSync(join(root, 'src', 'emails', 'logo.ts'), `// Generated by scripts/email-logo.mjs from logo/elare logo.png — do not edit.
/** The Élaré emblem (${SIZE}×${SIZE} PNG, ${png.length} bytes), embedded in every email. */
export const LOGO_PNG_BASE64 =
  '${png.toString('base64')}';
`);
console.log(`src/emails/logo.ts: ${SIZE}x${SIZE}, ${(png.length / 1024).toFixed(1)} KB`);
